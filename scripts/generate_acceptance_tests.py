#!/usr/bin/env python3
"""Generate concrete XCTest methods from the .feature files.

The .feature files in pipeUITests/Features/ are the source of truth. XCTest needs
real (selector-addressable) test methods for `-only-testing` filtering and crash
recovery, so we generate one thin `test…` per scenario, each delegating to
`runScenario(feature:scenario:)`. Each feature file gets its own subclass of
`AcceptanceTests` because Xcode's parallel testing distributes work by class —
one class would pin every scenario to a single simulator. The generated file
is checked in and kept in sync by a quality gate (`--check`).

Usage:
  python3 scripts/generate_acceptance_tests.py          # write the generated file
  python3 scripts/generate_acceptance_tests.py --check  # fail if out of date
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FEATURES_DIR = REPO / "pipeUITests" / "Features"
OUTPUT = REPO / "pipeUITests" / "AcceptanceTests.generated.swift"

HEADER = """// @generated by scripts/generate_acceptance_tests.py — DO NOT EDIT.
// Source of truth: pipeUITests/Features/*.feature
// Regenerate with: python3 scripts/generate_acceptance_tests.py
import XCTest
"""


def parse_features():
    """Return [(feature_name, file_name, [scenario_name, ...]), ...]."""
    out = []
    for path in sorted(FEATURES_DIR.glob("*.feature")):
        feature_name = None
        scenarios = []
        for raw in path.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if line.startswith("Feature:"):
                feature_name = line[len("Feature:"):].strip()
            elif line.startswith("Scenario:"):
                scenarios.append(line[len("Scenario:"):].strip())
        if feature_name:
            out.append((feature_name, path.name, scenarios))
    return out


def selector_fragment(name):
    """Mirror AcceptanceTests.sanitize: non-alphanumerics become underscores."""
    return re.sub(r"[^0-9A-Za-z]", "_", name)


def swift_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def class_name(file_name):
    """audio_language.feature -> AudioLanguageFeatureTests."""
    stem = Path(file_name).stem
    return "".join(part.capitalize() for part in re.split(r"[^0-9A-Za-z]+", stem) if part) + "FeatureTests"


def render():
    lines = [HEADER]
    for feature_name, file_name, scenarios in parse_features():
        lines.append(f"\n/// {feature_name}")
        lines.append(f"final class {class_name(file_name)}: AcceptanceTests {{\n")
        for scenario in scenarios:
            method = "test_" + selector_fragment(scenario)
            lines.append(f"    func {method}() {{")
            lines.append(
                f'        runScenario(feature: "{swift_escape(file_name)}", '
                f'scenario: "{swift_escape(scenario)}")'
            )
            lines.append("    }\n")
        lines.append("}\n")
    return "\n".join(lines)


def main():
    content = render()
    check = "--check" in sys.argv
    if check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print("✗ AcceptanceTests.generated.swift is out of date.")
            print("  Run: python3 scripts/generate_acceptance_tests.py")
            sys.exit(1)
        print("✓ Generated acceptance tests are in sync with .feature files.")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        n = sum(len(s) for _, _, s in parse_features())
        print(f"✓ Wrote {OUTPUT.relative_to(REPO)} ({n} scenarios).")


if __name__ == "__main__":
    main()
